//go:build ignore

// Run from the repository root: go run scripts/generate-search-dictionary.go
// Generates the browser/Go dictionary and migration from the pinned MIT-licensed
// go-pinyin dictionary. No database connection or external service is used.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"

	pinyin "github.com/mozillazg/go-pinyin"
)

func main() {
	if pinyin.Version != "0.21.0" {
		panic("review dictionary changes before changing the pinned source version")
	}
	characters := make([]int, 0, len(pinyin.PinyinDict))
	for character := range pinyin.PinyinDict {
		characters = append(characters, character)
	}
	sort.Ints(characters)
	dictionary := make(map[string]string, len(characters))
	var sql strings.Builder
	sql.WriteString("-- Generated by scripts/generate-search-dictionary.go from go-pinyin v0.21.0.\n-- MIT license and provenance: shared/search/README.md and LICENSE.go-pinyin.\n-- This migration only adds search data/functions; it does not change authorization.\nCREATE TABLE aiops_pinyin_dictionary(character text PRIMARY KEY, pinyin text NOT NULL);\nINSERT INTO aiops_pinyin_dictionary(character,pinyin) VALUES\n")
	for index, character := range characters {
		char := string(rune(character))
		reading := pinyin.SinglePinyin(rune(character), pinyin.Args{Style: pinyin.Normal})[0]
		reading = strings.ReplaceAll(reading, "ü", "v")
		dictionary[char] = reading
		if index > 0 {
			sql.WriteString(",\n")
		}
		fmt.Fprintf(&sql, "('%s','%s')", strings.ReplaceAll(char, "'", "''"), strings.ReplaceAll(reading, "'", "''"))
	}
	sql.WriteString(";\n\n")
	functions, err := os.ReadFile("scripts/search-functions.sql")
	check(err)
	sql.Write(functions)
	data, err := json.Marshal(dictionary)
	check(err)
	check(os.WriteFile("shared/search/pinyin.json", append(data, '\n'), 0644))
	check(os.WriteFile("migrations/019_search_pinyin.sql", []byte(sql.String()), 0644))
	fmt.Printf("Generated %d character readings\n", len(dictionary))
}

func check(err error) {
	if err != nil {
		panic(err)
	}
}
